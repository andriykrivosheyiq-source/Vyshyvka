  function rule(x, t, x0, x1, y){
    x.strokeStyle = t.line; x.lineWidth = 2;
    x.beginPath(); x.moveTo(x0, y); x.lineTo(x1, y); x.stroke();
  }

  /* ══════════ НИЖНЯ СМУГА ══════════
     Ціна, під нею стара ціна й знижка; далі термін; праворуч — застереження.

     Стара ціна НЕ вводиться окремо: беремо базову ціну самої позиції за тим
     самим правилом, що й сторінка пропозиції — показуємо, лише якщо вона
     більша за поточну. Інакше картка й КП рано чи пізно розійшлися б у тому,
     скільки саме клієнт економить, а розходження тут коштує довіри.

     Застереження стоїть третьою колонкою праворуч, а не рядком упоперек
     аркуша. Це виноска: збоку дрібним вона читається як виноска, а на всю
     ширину під числами — як попередження, яке ми чомусь кричимо. */
  function oldPrice(card, show){
    if(!show('old')) return null;
    var base = +card.base || 0, unit = +card.unit || 0;
    if(!unit || base <= unit) return null;
    /* «/шт» стоїть і на старій ціні теж. Без нього поруч опинялись два
       числа в різних одиницях — «2 499 грн» і «1 999 грн/шт», — і стара
       ціна читалась як сума за все замовлення, а не за виріб. */
    return { was: money(base) + '/шт', off: '−' + Math.round((base - unit) / base * 100) + ' %' };
  }
  /* Текстова колонка нижньої смуги: підпис капітеллю, під ним текст, який
     сам добирає кегль, доки не вміститься у відведені рядки. Опис і
     примітка — це одна й та сама будова, і код у них має бути один: інакше
     дві сусідні колонки почнуть по-різному переносити рядки. */
  function textCell(x, t, lab, s, X, yLab, w, size, color, maxLines){
    eyebrow(x, lab, X, yLab, t.dim, 21);
    x.fillStyle = color;
    var n = size, lines;
    do {
      x.font = '400 ' + n + 'px ' + t.body;
      lines = wrap(x, s, w, 0);
      n -= 1;
    } while(lines.length > maxLines && n > 11);
    var step = Math.round(n * 1.4);
    lines.forEach(function(ln, i){ x.fillText(ln, X, yLab + 32 + i * step); });
  }
  /* Характеристики — ОДНА КОЛОНКА, рядок за рядком, у тому порядку, у
     якому їх заведено в картці товару.

     Дві колонки тут пробували: читач мусить сам вирішити, чи йти йому
     вниз, чи вбік, — і на п'яти коротких парах ця робота не окупається.
     Один стовпчик читається згори вниз без жодного рішення.

     Назва й значення в одному рядку: назва сірим, значення чорнилом
     одразу за нею. Пара тримається разом, а колонка лишається вузькою. */
