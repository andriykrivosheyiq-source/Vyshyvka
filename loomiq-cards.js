    rows.forEach(function(r){ w = Math.max(w, x.measureText(r).width); });
    x.fillStyle = tint(t.dim, 0.45);
    x.textAlign = 'right';
    var y0 = mid + 7 - (rows.length - 1) * 13;
    rows.forEach(function(r, i){ x.fillText(r, right, y0 + i * 26); });
