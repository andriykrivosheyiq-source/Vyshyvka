/* РЕКОМЕНДОВАНА ПОЗИЦІЯ НЕ ПЛАТИТЬ ЗА ВЖЕ ЗРОБЛЕНИЙ МАКЕТ.

   Ми домовились так: якщо цей самий малюнок уже стоїть на погодженій
   частині замовлення, то в рекомендованому товарі підготовки макета немає —
   роботу зроблено, платити за неї другий раз ні за що. Саме звідси й
   береться вигода допродажу: та сама вишивка, але без разової.

   Рушій це вмів завжди — по ознаці `upsell` він кладе допродаж в ОКРЕМЕ
   відро разових і звіряє його з макетами погодженої частини. А конструктор
   цю ознаку не ставив. Виходило, що на екрані збирання рекомендована
   позиція коштувала як звичайна (1005 ₴/шт), а в самій пропозиції — дешевше
   (882 ₴/шт): два екрани того самого замовлення казали різні числа, і
   довіряти не можна було жодному.

   Перевіряємо рушій на числах і те, що конструктор ознаку таки ставить —
   на обох шляхах, якими описи позицій до рушія доходять: і готовим
   кошиком, і чернеткою позиції, яку менеджер саме зараз крутить.

   Запуск:  node tests/reco-upsell.mjs      (з кореня репозиторію)  */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
globalThis.SITE_CONTENT = { pricing: {
  minMarginPct: 0, tiers: [{ from:1, coef:1 }], garmentTiers: [{ from:1, coef:1 }],
  methods: { embro: { orderFee:850, orderCost:300, sketchFee:350, sketchCost:150,
                      pieceFee:75, pricePer1000mm2:42, tiers:[{ from:1, coef:1 }] },
             dtf: { orderFee:900, tiers:[{ from:1, coef:1 }] } } } };
require(path.join(ROOT, 'loomiq-pricing.js'));

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

const ЛОГО = '4'.repeat(432) + '|' + '4'.repeat(144);
/* Відбиток, який із ЛОГО не збігається зовсім, — але це той самий файл.
   Так виглядає той самий логотип, покладений на виріб іншої форми: рендер
   інший, пікселі інші, адреса та сама. */
const ІНАКШІ_ПІКСЕЛІ = '0'.repeat(432) + '|' + '4'.repeat(144);
const ФАЙЛ = 'https://loomiq.example/logo.png';
const поз = (gid, units, up, fp, url) => ({ method:'embro', gid, units, base:1000,
  coefPart:200, basePart:0, minPart:0, pieceFee:75, bare:false, upsell:!!up,
  designs:[fp || ЛОГО], designUrls:[url === undefined ? '' : url],
  designKinds:['img'], designMm2:[2000], dtfCols:[] });

/* ── 1. З ознакою: макет уже оплачено, допродаж дешевший ─────────────── */
console.log('\n── Погоджена позиція + рекомендована з тим самим логотипом');
{
  const r = window.LQ.priceOrder([ поз('hoodie', 3), поз('cap', 3, true) ]);
  const осн = r[0].parts, реко = r[1].parts;
  ok(реко.upsell === true, 'рушій бачить допродаж', 'ознака допродажу не дійшла до рушія');
  ok(реко.feeShare === 0 && !(реко.feeLines || []).length && !(реко.sketches || []).length,
     'рекомендована за макет не платить',
     'рекомендована платить за макет: ' + реко.feeShare + ' ₴');
  ok(((реко.designNos || [])[0] || {}).done === true,
     'у розкладі написано, що макет оплачено основними позиціями',
     'розклад не каже, чому разової немає — цифра виглядатиме як помилка');
  /* Погоджена частина платить свою разову ЦІЛКОМ і лише на свої вироби:
     3 шт, 850 ÷ 3. Допродаж у тираж разової не входить — інакше знижка
     їхала б від кількості, яку клієнт ще не підтвердив. */
  ok(((осн.feeLines || [])[0] || {}).units === 3,
     'погоджена частина ділить разову на свої 3 шт',
     'разова поділилась не на 3 шт: ' + ((осн.feeLines || [])[0] || {}).units);
  ok(r[1].unit < r[0].unit,
     'допродаж дешевший за погоджену позицію: ' + r[1].unit + ' проти ' + r[0].unit,
     'допродаж вийшов не дешевшим: ' + r[1].unit + ' і ' + r[0].unit);
}

/* ── 2. Той самий ФАЙЛ, але пікселі розійшлись ───────────────────────── */
console.log('\n── Рекомендована з тим самим файлом, але іншими пікселями');
{
  /* Саме на цьому рушій і ламався. Усередині прогону копії одного малюнка
     зводить адреса файлу, а перевірка «макет уже оплачено погодженою
     частиною» лишалась при самих пікселях — і допродаж платив повну
     підготовку за роботу, яку склад уже оплатив. */
  const r = window.LQ.priceOrder([
    поз('hoodie', 3, false, ЛОГО, ФАЙЛ),
    поз('cap', 3, true, ІНАКШІ_ПІКСЕЛІ, ФАЙЛ) ]);
  const реко = r[1].parts;
  ok(реко.feeShare === 0 && !(реко.feeLines || []).length,
     'рекомендована впізнала свій макет за файлом і не платить',
     'рекомендована платить за вже оплачений макет: ' + реко.feeShare + ' ₴');
  ok(((реко.designNos || [])[0] || {}).done === true,
     'у розкладі так і написано — оплачено основними позиціями',
     'розклад не каже, що макет уже оплачено');
}

/* ── 3. Без ознаки: та сама поломка, яку й лагодили ──────────────────── */
console.log('\n── Та сама пара, але ознаку допродажу втрачено');
{
  const r = window.LQ.priceOrder([ поз('hoodie', 3), поз('cap', 3) ]);
  ok(r[0].unit === r[1].unit && r[1].parts.feeShare > 0,
     'без ознаки рекомендована платить разову навпіл — саме це й розходило екрани',
     'перевірка втратила сенс: числа без ознаки й з нею однакові');
}

/* ── 4. Конструктор ознаку ставить — на обох шляхах ──────────────────── */
console.log('\n── Конструктор позначає рекомендовані позиції');
{
  const ctor = fs.readFileSync(path.join(ROOT, 'loomiq-constructor.js'), 'utf8');
  ok(/function descUpsell\(/.test(ctor), 'позначка є',
     'позначки немає — рекомендовані знову рахуються як погоджені');
  /* Описи доходять до рушія двома шляхами: готовим кошиком (cartDescriptors)
     і кошиком із чернеткою позиції, яку менеджер крутить просто зараз
     (descriptorsWithDraft). Ознака потрібна на обох, інакше ціна стрибає
     рівно в мить збереження. */
  const скільки = (ctor.match(/descUpsell\(/g) || []).length;
  ok(скільки >= 4, 'позначка стоїть на всіх шляхах до рушія (' + скільки + ')',
     'позначку загубили на частині шляхів: викликів лише ' + скільки);
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
