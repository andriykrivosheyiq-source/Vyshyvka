/* СТОРІНКА САМА ПОМІЧАЄ, ЩО ВИЙШЛА НОВА ВЕРСІЯ.

   Найдорожча поломка цієї роботи — не в коді. Зміни залито, збірка пройшла,
   а менеджер відкриває адмінку й бачить учорашню: позначка `?v=` рятує
   лише скрипти, а в самої сторінки адреси з позначкою немає, тож браузер
   тримає її стільки, скільки схоче. Зовні це не відрізнити від «нічого не
   зроблено» — і кілька разів поспіль так і виглядало.

   Було й гірше: номер збірки рахувався ЛИШЕ з файлів рушіїв. Правка в самій
   сторінці — розмітка, стилі, обробники — номера не рухала взагалі. Тобто
   сторінка змінилась, а всі позначки лишились ті самі.

   Перевіряємо три речі:
     1. номер збірки враховує й сторінки, а не тільки рушії;
     2. він однаковий на двох прогонах збірки — інакше кожен прогін
        оголошував би «вийшла нова версія» на порожньому місці;
     3. сторінка знає свій номер і вміє спитати збірку про свіжий.

   Запуск:  node tests/fresh-build.mjs      (з кореня репозиторію)  */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

let bad = 0;
const ok = (c, good, wrong) => { console.log('  ' + (c ? good + ' ✓' : wrong + ' ✗')); if(!c) bad++; };

/* ПРАЦЮЄМО В КОПІЇ, А НЕ В РЕПОЗИТОРІЇ.

   Перевірка мусить правити сторінку й перезбирати — а набір іде паралельно,
   і сусідні перевірки в цю мить відкривають ті самі файли браузером. Перша
   ж спроба зробити це на місці повалила три чужі перевірки: вони побачили
   напівзібрану адмінку. Копія коштує секунду й прибирає весь клас таких
   зіткнень. */
const ROOT = fs.mkdtempSync(path.join(os.tmpdir(), 'lq-build-'));
fs.cpSync(REPO, ROOT, { recursive: true,
  filter: s => !/(^|\/)(\.git|node_modules)(\/|$)/.test(s.slice(REPO.length)) });
process.on('exit', () => { try{ fs.rmSync(ROOT, { recursive:true, force:true }); }catch(e){} });

const зібрати = () => {
  execFileSync('python3', [path.join(ROOT, 'tools/build-sites.py')], { cwd: ROOT });
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'build.json'), 'utf8')).v;
};
const адмінка = () => fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');

console.log('\n── Номер збірки');
const v1 = зібрати();
ok(/^[a-z0-9]{6,}$/.test(v1), 'збірка лишає номер у build.json: ' + v1,
   'build.json без номера: ' + v1);
/* Двічі поспіль — той самий. Інакше кожен прогін оголошував би нову версію
   на порожньому місці, і смужку перестали б помічати за тиждень. */
ok(зібрати() === v1, 'повторний прогін дає той самий номер',
   'номер стрибає між прогонами — смужка кричала б щоразу');

ok(адмінка().indexOf("LQ_VER = '" + v1 + "'") >= 0,
  'сторінка знає свій номер',
  'номер у сторінку не підставився');

console.log('\n── Правка в самій сторінці теж міняє номер');
{
  /* Саме цього й бракувало: номер брався лише з файлів рушіїв, тож правка
     розмітки чи стилів адмінки лишалась непоміченою. */
  const p = path.join(ROOT, 'loomiqadmin.html');
  const було = fs.readFileSync(p, 'utf8');
  fs.writeFileSync(p, було.replace('<body', '<body data-lq-test="1"'));
  const v2 = зібрати();
  fs.writeFileSync(p, було);
  const v3 = зібрати();
  ok(v2 !== v1, 'змінили сторінку — номер інший',
     'правка сторінки номера не зрушила: ' + v2 + ' = ' + v1);
  ok(v3 === v1, 'повернули як було — номер повернувся',
     'номер не повернувся після відкату: ' + v3 + ' ≠ ' + v1);
}

console.log('\n── Сторінка вміє спитати про свіжу версію');
{
  const h = адмінка();
  ok(/build\.json/.test(h) && /cache:'no-store'|cache: *'no-store'/.test(h),
    'питає build.json повз кеш — інакше відповідь була б така сама стара',
    'перевірки свіжої версії в сторінці немає');
  ok(/lq-newver/.test(h),
    'і має що показати, коли версія розійшлась',
    'смужки про нову версію немає');
  /* Мовчки не перезавантажуємо ніколи: людина може саме зараз писати
     клієнту, і втрачений текст дорожчий за свіжу розмітку. */
  ok(!/location\.reload\(\s*\)/.test(h.slice(0, h.indexOf('lq-newver') + 3000)) ||
     /Оновити/.test(h),
    'оновлення пропонується кнопкою, а не робиться само',
    'сторінка перезавантажується без питання — так втрачають недописані листи');
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\nсвіжа версія більше не залежить від памʼяті браузера');
process.exit(bad ? 1 : 0);
