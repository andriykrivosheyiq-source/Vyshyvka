/* ТОЙ САМИЙ МАКЕТ ВИЗНАЧАЄ ФАЙЛ, А НЕ СХОЖІСТЬ ПІКСЕЛІВ.

   Питання коштує грошей: один макет — одна підготовка на 850 ₴, два — ще
   й ескіз на 350 ₴, і ділиться це на різні вироби.

   Спокуса розвʼязати його схожістю пікселів велика й оманлива. Її вже
   пробували: поріг схожості підняли з 3% до 8%, щоб копії одного логотипа
   зводились самі. На живому замовленні (1000084) виявилось, що так не
   можна ніколи:

     • зад ↔ зад, той самий файл ....................... 0.0%
     • перед ↔ перед, той самий логотип, два файли ..... 4.0%
     • перед ↔ зад, РІЗНІ логотипи ..................... 4.8%

   Копії одного малюнка й геть різні малюнки стоять поруч — 4.0 і 4.8.
   Порогу, який розділив би їх, не існує. За 8% усі чотири дизайни того
   замовлення злились в один макет, і передній логотип зник із рахунку
   зовсім: клієнт отримав роботу, за яку ніхто не заплатив.

   Тому правило таке: зводить АДРЕСА ФАЙЛУ, а схожість лишається строгою
   (3%) і ловить хіба що перезбереження того самого файлу. Щоб адреси
   збіглись, макет кладуть із галереї макетів — вона для того й існує.

   Відстані тут узяті з того самого замовлення, тож перевірка тримає саме
   ту межу, на якій рушій колись зламався.

   Запуск:  node tests/design-twin.mjs      (з кореня репозиторію)  */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
globalThis.SITE_CONTENT = { pricing: {
  minMarginPct: 0, tiers: [{ from:1, coef:1 }], garmentTiers: [{ from:1, coef:1 }],
  methods: { embro: { orderFee:850, orderCost:300, sketchFee:350, sketchCost:150,
                      pieceFee:75, pricePer1000mm2:42, tiers:[{ from:1, coef:1 }] },
             dtf: { orderFee:900, tiers:[{ from:1, coef:1 }] } } } };
require(path.join(ROOT, 'loomiq-pricing.js'));

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

/* Відбиток — 12×12 клітинок кольору (три цифри на клітинку) і 12×12
   прозорості через «|». Одна змінена цифра кольору додає 3/(4·432·4) =
   1/2304 відстані, тож 92 цифри дають рівно ті 4%, на яких у живому
   замовленні стоять і копії одного логотипа, і різні логотипи. */
const COL = 432, ALP = 144;
const відбиток = (n, ц) => (ц.repeat(n) + '4'.repeat(COL - n)) + '|' + '4'.repeat(ALP);
const ОСН    = відбиток(0, '4');
const ЗА_4   = відбиток(92, '5');    // ≈4% — і копія, і чужий малюнок бувають тут
const ЗА_1   = відбиток(20, '5');    // ≈0.9% — так близько буває лише той самий файл

console.log('\n── Межа схожості лишається строгою');
{
  const d = window.LQ.fpDistance;
  ok(d(ОСН, ОСН) === 0, 'той самий рядок — відстань 0', 'той самий рядок не збігається');
  ok(window.LQ.sameFingerprint(ОСН, ЗА_1),
     'майже однакові (' + d(ОСН, ЗА_1).toFixed(3) + ') — один дизайн',
     'перезбережений той самий файл рахується як два: ' + d(ОСН, ЗА_1).toFixed(3));
  /* ГОЛОВНА ПЕРЕВІРКА ЦЬОГО ФАЙЛУ. На 4% стоять і копії, і різні логотипи —
     отже зводити на цій відстані не можна нікому, інакше чужий дизайн
     мовчки зникає з рахунку. */
  ok(!window.LQ.sameFingerprint(ОСН, ЗА_4),
     'на 4% (' + d(ОСН, ЗА_4).toFixed(3) + ') уже НЕ зводимо — там живуть і різні логотипи',
     'поріг знову задерли: різні логотипи зіллються в один макет і зникнуть із рахунку');
}

const поз = (gid, units, designs, urls) => ({ method:'embro', gid, units, base:1000,
  coefPart:200, basePart:0, minPart:0, pieceFee:75, bare:false,
  designs: designs, designUrls: urls || designs.map(() => ''),
  designKinds: designs.map(() => 'img'), designMm2: designs.map(() => 2000), dtfCols:[] });
const прогін = list => window.LQ.priceOrder(list);

/* ── Саме те замовлення, на якому це знайшлось ───────────────────────── */
console.log('\n── Замовлення 1000084: спільний зад, різні переди');
{
  /* Дві позиції по 2 і 3 шт. Ззаду той самий ФАЙЛ на обох — має ділитись
     на всі 5. Спереду два різні файли — кожен свій макет, і кожен має
     потрапити в рахунок: саме вони й зникали. */
  const ЗАД = 'https://cdn/765/ypcq3ubzjsuhlmkmomys.png';
  const r = прогін([
    поз('hoodie', 2, [відбиток(92, '5'), ОСН], ['https://cdn/126/j4thagms.png', ЗАД]),
    поз('hoodieover', 3, [відбиток(92, '3'), ОСН], ['https://cdn/370/ngdfqvu5.png', ЗАД])
  ]);
  const лінії = r.flatMap(x => x.parts.feeLines || []);
  const ескізи = r.flatMap(x => x.parts.sketches || []);
  ok(лінії.length === 2 && лінії.every(f => f.units === 5),
     'задній логотип — один макет на всі 5 шт',
     'задній логотип поділився не на 5: ' + лінії.map(f => f.units).join('/'));
  ok(ескізи.length === 2,
     'обидва передні логотипи потрапили в рахунок окремими ескізами',
     'передні логотипи в рахунку не зʼявились: ескізів ' + ескізи.length);
  const по = ескізи.map(s => s.units).sort();
  ok(по.join('/') === '2/3',
     'кожен передній ділиться на свої вироби (2 і 3)',
     'передні поділились не на свої вироби: ' + по.join('/'));
}

/* ── Той самий файл зводить навіть різні пікселі ─────────────────────── */
console.log('\n── Один файл на обох позиціях');
{
  const ФАЙЛ = 'https://cdn/logo.png';
  const r = прогін([ поз('hoodie', 2, [ОСН], [ФАЙЛ]),
                     поз('tee', 3, [ЗА_4], [ФАЙЛ]) ]);
  ok(!r.flatMap(x => x.parts.sketches || []).length &&
     r.flatMap(x => x.parts.feeLines || []).every(f => f.units === 5),
     'той самий файл — один макет на 5 шт, хай пікселі й розійшлись',
     'той самий файл розʼїхався на два макети');
}

/* ── Розклад каже, ЧОМУ це окремий макет ─────────────────────────────── */
console.log('\n── Причина, а не вирок');
{
  const r = прогін([ поз('hoodie', 2, [ОСН], ['https://cdn/a.png']),
                     поз('tee', 3, [ЗА_4]) ]);
  const з = (r[0].parts.designNos || [])[0] || {};
  const без = (r[1].parts.designNos || [])[0] || {};
  ok(з.byFile === true && без.byFile === false,
     'видно, у кого адреса файлу є, а в кого немає',
     'ознака адреси файлу не доїхала до розкладу');
  ok(typeof з.near === 'number' && з.near > 0.03,
     'видно відстань до найближчого макета: ' + (з.near || 0).toFixed(3),
     'відстань до найближчого макета не порахована: ' + з.near);
  const admin = fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');
  ok(/найближчий інший макет/.test(admin) && /адреси файлу немає/.test(admin),
     'розклад в адмінці друкує обидві причини',
     'адмінка причину не друкує — питання «чому» знову без відповіді');
  ok(/function engineVersion\(/.test(admin) && /t-calc-ver/.test(admin),
     'версія рушія видна в розкладі',
     'версії рушія на екрані немає');
}

/* ── Слово менеджера: «це той самий макет» ───────────────────────────── */
console.log('\n── Зведено руками');
{
  /* Пікселі відповісти не можуть, а менеджер бачить обидва малюнки. Його
     рішення записується як канонічна АДРЕСА ФАЙЛУ — і далі працює те саме
     правило, що зводить справжні копії. Окремої логіки для «зведених
     вручну» немає навмисно: одна робота — одне правило. */
  const ФАЙЛ = 'https://cdn/a.png';
  const r = прогін([ поз('hoodie', 2, [ОСН], [ФАЙЛ]),
                     поз('tee', 3, [ЗА_4], [ФАЙЛ]) ]);   // менеджер підмінив адресу
  ok(!r.flatMap(x => x.parts.sketches || []).length &&
     r.flatMap(x => x.parts.feeLines || []).every(f => f.units === 5),
     'зведені руками макети діляться на всі 5 шт',
     'ручне зведення не спрацювало');
  const admin = fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');
  const ctor = fs.readFileSync(path.join(ROOT, 'loomiq-constructor.js'), 'utf8');
  ok(/function applySameFix\(/.test(admin) && /act === 'sameFix'/.test(admin),
     'адмінка приймає й зберігає це рішення',
     'рішення нікуди не записується — згорить на переході до наступної позиції');
  /* Рішення має лягти в розрахунок ПЕРЕД цінами, у всіх трьох місцях:
     розклад картки, перерахунок замовлення й насіння для конструктора. */
  ok((admin.match(/applySameFix\(o\)/g) || []).length >= 3,
     'і застосовує його скрізь, де рахуються ціни',
     'десь рахунок іде повз рішення менеджера — два екрани покажуть різне');
  ok(/data-mgr-same/.test(ctor) && /l\.sameAs/.test(ctor),
     'у прорахунку є кнопка, і вона пише рішення на шар',
     'кнопки «це той самий макет» немає');
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
