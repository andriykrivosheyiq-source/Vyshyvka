/* ТОЙ САМИЙ ЛОГОТИП — ОДИН МАКЕТ, ХАЙ БИ ЯК РОЗІЙШЛИСЬ ПІКСЕЛІ.

   Найчастіша скарга на прорахунок звучала так: логотип на вигляд один, я
   поклав його з галереї макетів на всі вироби — а підготовка ділиться не на
   весь тираж, 850 ÷ 3 замість 850 ÷ 5.

   Причин було дві, і обидві тут перевіряються.

   1. ПОРІГ СХОЖОСТІ БУВ ЗАНАДТО СТРОГИЙ. Той самий файл, покладений окремо
      на дві позиції, після зняття фону дає пікселі, що розходяться на 5–7%,
      а зводились лише ті, що ближче 3%. Рушій бачив два макети — і був
      формально правий, а по суті ні. Тепер поріг 8%: копії зводяться, різні
      малюнки (11–23%) лишаються різними.

   2. «МАКЕТ УЖЕ ОПЛАЧЕНО» ПИТАЛО ТІЛЬКИ ПРО ПІКСЕЛІ. Усередині прогону
      копії одного малюнка зводить адреса файлу, а перевірка, за якою
      рекомендована позиція не платить за готовий макет, лишалась при самих
      пікселях. Тому допродаж із тим самим ФАЙЛОМ платив підготовку вдруге.
      Тепер обидві перевірки питають одне й те саме.

   Рушій крутиться просто в node: він нічого, крім window.SITE_CONTENT, не
   просить, а браузер тут лише сповільнив би перевірку чисел.

   Запуск:  node tests/design-twin.mjs      (з кореня репозиторію)  */
import { createRequire } from 'node:module';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
globalThis.SITE_CONTENT = { pricing: {
  minMarginPct: 0, tiers: [{ from:1, coef:1 }], garmentTiers: [{ from:1, coef:1 }],
  methods: { embro: { orderFee:850, orderCost:300, sketchFee:350, sketchCost:150,
                      pieceFee:75, pricePer1000mm2:42, tiers:[{ from:1, coef:1 }] },
             dtf: { orderFee:900, tiers:[{ from:1, coef:1 }] } } } };
require(path.join(ROOT, 'loomiq-pricing.js'));

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

/* ВІДБИТКИ З НАВМИСНОЮ ВІДСТАННЮ.

   Відбиток — 12×12 клітинок кольору (три цифри на клітинку) і 12×12
   прозорості, розділені «|». Відстань — середня різниця цифр, зважена 3 до
   1 на користь кольору. Звідси й рахунок: одна змінена цифра кольору додає
   3/(4·432·4) = 1/2304 відстані.

   КОПІЯ відрізняється від ОСН на 150 цифр по одиниці: 150/2304 ≈ 0.065 —
   рівно те розходження, яке дає окремо знятий фон, і рівно те, на якому
   рушій колись ламався. ІНШИЙ — увесь колір інший, 0.75. */
const COL = 432, ALP = 144;
const ОСН   = '4'.repeat(COL) + '|' + '4'.repeat(ALP);
const КОПІЯ = '5'.repeat(150) + '4'.repeat(COL - 150) + '|' + '4'.repeat(ALP);
const ІНШИЙ = '0'.repeat(COL) + '|' + '4'.repeat(ALP);

console.log('\n── Відстані між відбитками');
{
  const d = window.LQ.fpDistance;
  ok(d(ОСН, ОСН) === 0, 'той самий файл — відстань 0', 'той самий файл не збігається');
  const dк = d(ОСН, КОПІЯ);
  ok(window.LQ.sameFingerprint(ОСН, КОПІЯ),
     'копія з окремо знятим фоном (' + dк.toFixed(3) + ') — той самий дизайн',
     'копія з окремо знятим фоном усе ще різний дизайн: ' + dк.toFixed(3));
  ok(!window.LQ.sameFingerprint(ОСН, ІНШИЙ),
     'інший малюнок (' + d(ОСН, ІНШИЙ).toFixed(2) + ') лишився іншим',
     'різні малюнки злились в один — поріг задерли надто високо');
}

const поз = (gid, units, fp, url, up) => ({ method:'embro', gid, units, base:1000,
  coefPart:200, basePart:0, minPart:0, pieceFee:75, bare:false, upsell:!!up,
  designs:[fp], designUrls:[url || ''], designKinds:['img'], designMm2:[2000], dtfCols:[] });
const прогін = list => window.LQ.priceOrder(list);

/* ── 1. Дві позиції, той самий логотип: 850 ÷ 5 ───────────────────────── */
console.log('\n── Один логотип на дві групи (2 + 3 шт)');
{
  /* Без адрес файлів зовсім — так виглядають замовлення, збережені до того,
     як конструктор почав їх писати. Зводити мусить сама схожість пікселів,
     інакше старі пропозиції лишаються з вигаданою кількістю макетів, поки
     менеджер не перезбереже кожну позицію окремо. */
  const r = прогін([ поз('hoodie', 2, ОСН), поз('tee', 3, КОПІЯ) ]);
  const лінії = r.flatMap(x => x.parts.feeLines || []);
  const ескізи = r.flatMap(x => x.parts.sketches || []);
  ok(!ескізи.length, 'додаткового ескізу немає — макет один',
     'зʼявився ескіз за другий макет, хоч малюнок той самий');
  ok(лінії.length === 2 && лінії.every(f => f.units === 5),
     'підготовка ділиться на всі 5 шт',
     'ділиться не на 5: ' + лінії.map(f => f.units).join('/'));
  ok(r[0].unit === r[1].unit,
     'обидві позиції коштують однаково: ' + r[0].unit + ' ₴/шт',
     'ціни розійшлись: ' + r[0].unit + ' і ' + r[1].unit);
}

/* ── 2. Справді різні малюнки: макетів два ───────────────────────────── */
console.log('\n── Два різні малюнки');
{
  const r = прогін([ поз('hoodie', 2, ОСН), поз('tee', 3, ІНШИЙ) ]);
  const лінії = r.flatMap(x => x.parts.feeLines || []);
  const ескізи = r.flatMap(x => x.parts.sketches || []);
  ok(лінії.length === 1 && ескізи.length === 1,
     'підготовка за перший макет і ескіз за другий',
     'вийшло не «підготовка + ескіз»: ' + лінії.length + '/' + ескізи.length);
  /* Повну підготовку несе БІЛЬША група (3 шт), меншій лишається ескіз на
     її 2 шт — щоб дорожча разова ділилась на більше виробів. */
  ok(лінії[0].units === 3 && ескізи[0].units === 2,
     'кожна разова ділиться на свої вироби (3 і 2)',
     'разові поділились не на свої вироби: ' +
       лінії[0].units + ' і ' + ескізи[0].units);
}

/* ── 3. Той самий ФАЙЛ, пікселі геть різні ───────────────────────────── */
console.log('\n── Один файл, відбитки розійшлись до невпізнання');
{
  /* Так буває, коли той самий файл лягає на вироби різної форми: рендер
     інший, пікселі інші. Адреса файлу при цьому спільна, і саме вона тут
     головна — на відміну від пікселів, розійтись вона не може. */
  const ФАЙЛ = 'https://loomiq.example/logo.png';
  const r = прогін([ поз('hoodie', 2, ОСН, ФАЙЛ), поз('tee', 3, ІНШИЙ, ФАЙЛ) ]);
  const ескізи = r.flatMap(x => x.parts.sketches || []);
  ok(!ескізи.length && r.flatMap(x => x.parts.feeLines || []).every(f => f.units === 5),
     'той самий файл — один макет на 5 шт',
     'той самий файл розʼїхався на два макети');
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
