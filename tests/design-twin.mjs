/* ПІДКАЗКА ПРО БЛИЗНЮКА: «схоже на сусідній макет».

   Найчастіше питання про разові звучить так: «логотип один, чому підготовка
   ділиться не на всі вироби». Рушій при цьому не помиляється — файл клали
   окремо на кожну позицію, після зняття фону пікселі вийшли різні, і для
   нього це два макети. Довести це він не може, а запідозрити — цілком:
   сусідній макет, значно ближчий за випадковий, майже напевно той самий
   логотип. Тоді він ставить на рядку разової `twin`, а екрани кажуть це
   вголос — рівно там, де людина читає число, яке її здивувало.

   Тут перевіряємо і сам рушій, і те, що жоден із трьох розкладів (картка,
   збирання пропозиції, конструктор) не втратив цю підказку.

   Рушій крутиться просто в node: він нічого, крім window.SITE_CONTENT, не
   просить, а браузер тут лише сповільнив би перевірку чисел.

   Запуск:  node tests/design-twin.mjs      (з кореня репозиторію)  */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
globalThis.SITE_CONTENT = { pricing: {
  minMarginPct: 0, tiers: [{ from:1, coef:1 }], garmentTiers: [{ from:1, coef:1 }],
  methods: { embro: { orderFee:850, orderCost:300, sketchFee:350, sketchCost:150,
                      pieceFee:75, pricePer1000mm2:42, tiers:[{ from:1, coef:1 }] },
             dtf: { orderFee:900, tiers:[{ from:1, coef:1 }] } } } };
require(path.join(ROOT, 'loomiq-pricing.js'));

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

/* ВІДБИТКИ З НАВМИСНОЮ ВІДСТАННЮ.

   Відбиток — 12×12 клітинок кольору (три цифри на клітинку) і 12×12
   прозорості, розділені «|». Відстань — середня різниця цифр, зважена 3 до
   1 на користь кольору. Звідси й рахунок нижче: одна змінена цифра кольору
   додає 3/(4·432·4) = 1/2304 відстані.

     • FP_SAME  = 0.03  — ближче за це рушій зводить у ОДИН макет;
     • близнюк  — далі за 0.03, але не далі за 0.12 (учетверо).

   БЛИЗ відрізняється від ОСН на 150 цифр по одиниці: 150/2304 ≈ 0.065 —
   рівно посередині вікна близнюка. ІНШИЙ — увесь колір інший, 0.75. */
const COL = 432, ALP = 144;
const ОСН   = '4'.repeat(COL) + '|' + '4'.repeat(ALP);
const БЛИЗ  = '5'.repeat(150) + '4'.repeat(COL - 150) + '|' + '4'.repeat(ALP);
const ІНШИЙ = '0'.repeat(COL) + '|' + '4'.repeat(ALP);

const d = window.LQ.fpDistance;
console.log('\n── Відстані між відбитками');
ok(d(ОСН, ОСН) === 0, 'той самий файл — відстань 0', 'той самий файл раптом не збігається');
const dб = d(ОСН, БЛИЗ);
ok(dб > 0.03 && dб <= 0.12,
   'близнюк у вікні підозри: ' + dб.toFixed(4), 'близнюк випав із вікна: ' + dб);
ok(d(ОСН, ІНШИЙ) > 0.12, 'інший малюнок далеко: ' + d(ОСН, ІНШИЙ).toFixed(3),
   'інший малюнок надто близько');

const поз = (gid, units, fp) => ({ method:'embro', gid, units, base:1000, coefPart:200,
  basePart:0, minPart:0, pieceFee:75, bare:false,
  designs:[fp], designKinds:['img'], designMm2:[2000], dtfCols:[] });
const прогін = list => window.LQ.priceOrder(list).map(x => x.parts);

/* ── 1. Той самий файл на обох групах: один макет, ділиться на всіх ───── */
console.log('\n── Один файл на дві позиції');
{
  const p = прогін([ поз('hoodie', 2, ОСН), поз('tee', 3, ОСН) ]);
  const лінії = p.flatMap(x => x.feeLines || []);
  const ескізи = p.flatMap(x => x.sketches || []);
  /* Рядок разової стоїть у розкладі КОЖНОЇ позиції — там він і потрібен, бо
     кожна платить свою частку. Макет при цьому один: та сама група, та сама
     сума, і ділиться вона на всі пʼять виробів. Додаткового ескізу немає
     зовсім — другого макета не існує. */
  ok(лінії.length === 2 && !ескізи.length,
     'одна підготовка на все замовлення, без ескізів',
     'вийшло не «підготовка без ескізів»: ' + лінії.length + '/' + ескізи.length);
  ok(лінії.every(f => f.gi === 0 && f.units === 5),
     'ділиться на 5 шт', 'ділиться не на 5: ' + лінії.map(f => f.units).join('/'));
  ok(лінії.every(f => !f.twin),
     'підказки немає — питати нема про що', 'підказка вискочила там, де все правильно');
}

/* ── 2. Близнюк: два макети, але рушій каже, що схоже на один ─────────── */
console.log('\n── Два схожі файли (той самий логотип, покладений двічі)');
{
  const p = прогін([ поз('hoodie', 2, ОСН), поз('tee', 3, БЛИЗ) ]);
  const лінії = p.flatMap(x => x.feeLines || []);
  const ескізи = p.flatMap(x => x.sketches || []);
  ok(лінії.length === 1 && ескізи.length === 1,
     'рушій бачить два макети: підготовка + ескіз',
     'вийшло не «підготовка + ескіз»: ' + лінії.length + '/' + ескізи.length);
  /* Повну підготовку платить БІЛЬША група — та, де виробів більше (3 шт);
     меншій лишається додатковий ескіз на її 2 шт. Саме звідси й беруться
     числа, з якими приходять питати: 850÷3 замість 850÷5. */
  ok(лінії[0] && лінії[0].units === 3 && ескізи[0] && ескізи[0].units === 2,
     'кожна разова ділиться лише на свої вироби (3 і 2)',
     'разові поділились не на свої вироби: ' +
       (лінії[0] || {}).units + ' і ' + (ескізи[0] || {}).units);
  ok(лінії.every(f => f.twin) && ескізи.every(f => f.twin),
     'обидва рядки позначені як близнюки', 'підказки на рядках разових немає');
}

/* ── 3. Справді різні малюнки: підказки бути не повинно ──────────────── */
console.log('\n── Два різні малюнки');
{
  const p = прогін([ поз('hoodie', 2, ОСН), поз('tee', 3, ІНШИЙ) ]);
  const усі = p.flatMap(x => (x.feeLines || []).concat(x.sketches || []));
  ok(усі.length === 2, 'два макети', 'макетів не два: ' + усі.length);
  ok(усі.every(f => !f.twin),
     'підказки немає — малюнки справді різні',
     'підказка збрехала: різні малюнки названо близнюками');
}

/* ── 4. Підказка дійшла до всіх трьох екранів ─────────────────────────── */
console.log('\n── Підказка на екранах');
{
  const admin = fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');
  const ctor = fs.readFileSync(path.join(ROOT, 'loomiq-constructor.js'), 'utf8');
  ok(/function twinNote\(/.test(admin), 'адмінка має підказку', 'в адмінці підказки немає');
  /* Три рядки разових в адмінці: «Як склалась ціна» в картці (підготовка й
     ескіз) і «розклад» у збиранні пропозиції. Порожній рядок на жодному з
     них — і менеджер знову дивиться на число без пояснення. */
  const скільки = (admin.match(/twinNote\(/g) || []).length;
  ok(скільки >= 5, 'підказка стоїть на ' + скільки + ' рядках розкладу',
     'підказку загубили: викликів twinNote лише ' + скільки);
  ok(/function близнюкПідказка\(/.test(ctor) &&
     (ctor.match(/близнюкПідказка\(/g) || []).length >= 3,
     'конструктор має підказку на підготовці й на ескізі',
     'у конструкторі підказки немає або вона не на всіх рядках');
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
