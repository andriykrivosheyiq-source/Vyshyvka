/* СПРАВЖНЄ ЗАМОВЛЕННЯ, СПРАВЖНІ ЧИСЛА.

   Усі інші перевірки рушія зібрані з вигаданих даних, і саме на цьому він
   одного разу зламався: поріг схожості підняли, спираючись на заміри з
   тестових малюнків, — а на живому замовленні виявилось, що копії одного
   логотипа й РІЗНІ логотипи стоять на однаковій відстані (4.0% і 4.8%).
   Два передні логотипи мовчки злились із заднім, зникли з рахунку, і
   клієнт отримав роботу, за яку ніхто не заплатив. Вигадані перевірки цього
   не побачили: у них такої пари просто не було.

   Тут лежить прорахунок справжнього замовлення 1000084 — модель цін,
   позиції й відбитки рівно такі, якими їх порахував браузер. Адреси файлів
   знеособлені: у рахунку важить лише те, які з них ОДНАКОВІ, а самі
   посилання на макети клієнта в репозиторії ні до чого. Відбитки справжні —
   у них і живуть ті 4.0% і 4.8%, заради яких усе це й написано.

   Склад замовлення:
     • ззаду один логотип, ОДНИМ файлом на обох групах — 5 шт;
     • спереду два РІЗНІ логотипи, по одному на групу — 2 шт і 3 шт.

   Отже: підготовка 850 ÷ 5, і два окремі ескізи 350 ÷ 2 і 350 ÷ 3.

   Запуск:  node tests/real-order.mjs      (з кореня репозиторію)  */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);
const F = JSON.parse(fs.readFileSync(path.join(ROOT, 'tests/fixtures/order-1000084.json'), 'utf8'));

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
globalThis.SITE_CONTENT = { pricing: F['модельЦін'] };
require(path.join(ROOT, 'loomiq-pricing.js'));

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

const r = window.LQ.priceOrder(F['позиції'], F['умови']);

/* ── Геометрія й ціна нанесення ───────────────────────────────────────

   Ці числа прийшли з браузера менеджера й мають лишатись незмінними, хай
   що ми робимо з разовими. Саме вони й показують, що ланцюг «розмір виробу
   з адмінки → частка полотна → мм² → ставка за 1000 мм²» цілий: якщо десь
   у ньому щось зрушить, зрушить і `appBase`. */
console.log('\n── Нанесення рахується від площі, як і рахувалось');
[{ app:460, garment:1430, base:150, min:0 },
 { app:490, garment:1540, base:150, min:0 }].forEach((чек, i) => {
  const p = r[i].parts;
  ok(p.appBase === чек.app, 'поз.' + (i+1) + ': нанесення ' + p.appBase + ' грн',
     'поз.' + (i+1) + ': нанесення ' + p.appBase + ' замість ' + чек.app);
  ok(p.garmentBase === чек.garment, 'поз.' + (i+1) + ': виріб ' + p.garmentBase + ' грн',
     'поз.' + (i+1) + ': виріб ' + p.garmentBase + ' замість ' + чек.garment);
  /* Старт нанесення й добивка до мінімальної ціни — окремі доданки
     всередині тієї ж суми. Найбільше нанесення бере найдорожчу мінімалку,
     тож порядок шарів теж перевіряється саме тут. */
  ok(p.basePart === чек.base && p.minPart === чек.min,
     'поз.' + (i+1) + ': старт ' + p.basePart + ' грн, добивки немає',
     'поз.' + (i+1) + ': старт/добивка ' + p.basePart + '/' + p.minPart +
       ' замість ' + чек.base + '/' + чек.min);
});
console.log('\n── Знижки за тираж');
[{ coef:0.94, gcoef:0.99 }, { coef:0.94, gcoef:0.99 }].forEach((чек, i) => {
  const p = r[i].parts;
  ok(p.coef === чек.coef && p.gcoef === чек.gcoef && p.groupQty === 5,
     'поз.' + (i+1) + ': нанесення ×' + p.coef + ', виріб ×' + p.gcoef + ', тираж 5 шт',
     'поз.' + (i+1) + ': шкали зрушили — ' + p.coef + '/' + p.gcoef + '/' + p.groupQty);
});

/* ── Разові: те, заради чого ця перевірка ────────────────────────────── */
console.log('\n── Макети: один спільний ззаду, два різні спереду');
{
  const лінії = r.flatMap(x => x.parts.feeLines || []);
  const ескізи = r.flatMap(x => x.parts.sketches || []);
  ok(лінії.length === 2 && лінії.every(f => f.fee === 850 && f.units === 5),
     'задній логотип — одна підготовка 850 ₴ на всі 5 шт',
     'задній логотип поділився не на 5: ' + JSON.stringify(лінії.map(f => f.fee + '÷' + f.units)));
  /* ГОЛОВНЕ. Саме ці два рядки зникали, коли поріг схожості підняли: робота
     була, а оплати за неї не було. */
  ok(ескізи.length === 2,
     'обидва передні логотипи в рахунку окремими ескізами',
     'передні логотипи зникли з рахунку: ескізів ' + ескізи.length);
  ok(ескізи.map(s => s.fee + '÷' + s.units).sort().join(' ') === '350÷2 350÷3',
     'кожен передній ділиться на свої вироби: 350÷2 і 350÷3',
     'ескізи поділились не так: ' + JSON.stringify(ескізи.map(s => s.fee + '÷' + s.units)));
}

console.log('\n── Ціна за штуку');
[2268, 2347].forEach((чек, i) => {
  ok(r[i].unit === чек, 'поз.' + (i+1) + ': ' + r[i].unit + ' ₴/шт',
     'поз.' + (i+1) + ': ' + r[i].unit + ' ₴/шт замість ' + чек);
});

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
