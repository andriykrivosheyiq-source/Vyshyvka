/* ГРОШОВИЙ ВОРКЕР: ЩОБ ВІН І АДМІНКА КАЗАЛИ ПРО ОДНЕ Й ТЕ САМЕ.

   Воркер і адмінка ніколи не зустрічаються: перший пише в Firestore, друга
   звідти читає. Між ними немає ні спільного коду, ні компілятора, який
   помітив би, що одна сторона пише `sum`, а друга читає `amount`. Помилка в
   такому місці не падає — вона просто дає порожній розділ Фінансів, і
   виглядає це як «банк не підключився».

   Плюс дві речі, за які тут платять грошима:

     • ДУБЛІ. Вебхук Монобанку приходить двічі, розклад питає Приват за ті
       самі дні щоразу, накладна НП висить у списку тижнями. Якщо кожен
       прогін додаватиме рядок, підсумок за тиждень виросте втричі — і цього
       ніхто не помітить, бо кожен окремий рядок правильний.

     • ЗНАК. Приват віддає суму модулем, а тип руху — окремою літерою.
       Загублений мінус перетворює витрату на дохід, і підсумок стає
       неправдою, яка виглядає як удача.

   І головне правило всієї роботи: у репозиторії не може бути жодного ключа.

   Запуск:  node tests/money-worker.mjs      (з кореня репозиторію)  */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
let bad = 0;
const ok = (c, good, wrong) => { console.log('  ' + (c ? good + ' ✓' : wrong + ' ✗')); if(!c) bad++; };

const worker = fs.readFileSync(path.join(ROOT, 'worker/money.js'), 'utf8');
const admin  = fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');
const toml   = fs.readFileSync(path.join(ROOT, 'worker/wrangler.money.toml'), 'utf8');
const readme = fs.readFileSync(path.join(ROOT, 'worker/README.md'), 'utf8');
const { _pure } = await import(path.join(ROOT, 'worker/money.js'));

console.log('\n── Воркер і адмінка пишуть про одне');
/* Адмінка читає рух як `{at, amount, acc, counter, desc, orderId, tag}`.
   Воркер мусить класти рівно ці імена — інакше Фінанси лишаться порожні, а
   виглядатиме це як «банк не підключився». */
['at', 'amount', 'acc', 'counter', 'desc'].forEach(k => {
  ok(new RegExp('\\b' + k + ':').test(worker) && new RegExp('p\\.' + k + '\\b').test(admin),
    'поле «' + k + '» однакове з обох боків',
    'поле «' + k + '» розходиться: воркер і адмінка читають різне');
});
/* Колекція теж одна. Друга називалась би так само правдоподібно. */
ok(/payments\//.test(worker) && /collection\('payments'\)/.test(admin),
  'і колекція та сама — payments',
  'воркер пише не в ту колекцію, з якої читає адмінка');

/* Правила бази мусять пускати адмінку до рухів. Доти правила для payments
   не було зовсім: воркер писав (службовому акаунту правила не заважають),
   а адмінка не могла прочитати — і Фінанси лишались порожні (03.10). */
const rules = fs.readFileSync(path.join(ROOT, 'firestore.rules'), 'utf8');
ok(/match \/payments\/\{id\}\s*\{[^}]*allow read/.test(rules),
  'правила бази пускають адмінку читати рухи (payments)',
  'у firestore.rules немає правила для payments — адмінка не побачить жодного руху');

console.log('\n── Ручну роботу воркер не затирає');
/* У документі вже можуть лежати `orderId` і `tag`, проставлені людиною.
   Повний перезапис документа щоночі стирав би їх — і привʼязка платежів,
   зроблена руками за тиждень, зникала б без жодного повідомлення. */
ok(/updateMask\.fieldPaths/.test(worker),
  'пише лише свої поля: привʼязка до замовлення й підпис лишаються людськими',
  'воркер перезаписує документ цілком — ручна привʼязка щоразу зникатиме');
ok(!/\borderId\s*:/.test(worker) && !/\btag\s*:/.test(worker),
  'і сам у них не лізе: банк не знає, чиї це гроші й чим вони є',
  'воркер пише orderId або tag — тобто затирає рішення людини');

console.log('\n── Той самий рух не подвоюється');
/* Стійкий номер із джерела — єдине, що робить повторний прогін нешкідливим. */
['mono_', 'privat_', 'np_'].forEach(p => {
  ok(worker.indexOf("'" + p) >= 0,
    'у рухів з «' + p.replace('_', '') + '» свій стійкий номер',
    'рухи з «' + p.replace('_', '') + '» пишуться без стійкого номера — будуть дублі');
});
ok(/payments\/' \+ p\.id/.test(worker),
  'і запис іде саме в документ із цим номером, а не додає новий',
  'запис створює новий документ щоразу — підсумок ростиме сам собою');

console.log('\n── Знак суми не губиться');
ok(/дохід \? сума : -сума/.test(worker),
  'витрата Привату лягає з мінусом: він віддає модуль, тип — окремою літерою',
  'знак суми Привату не ставиться — витрати рахуватимуться як дохід');
ok(/\/ 100/.test(worker),
  'а копійки Монобанку переводяться в гривні',
  'суми Монобанку лягають у копійках — підсумок буде в сто разів більший');

console.log('\n── Дати приводяться до одного вигляду');
/* Адмінка сортує рухи порівнянням РЯДКІВ і питає `where('at','>=',ISO)`.
   Дата в іншому форматі не зламається — вона просто тихо стане не там. */
const дати = [
  ['Приват', _pure.privatIso({ DATE_TIME_DAT_OD_TIM_P:'01.02.2026 13:45:00' })],
  ['Приват без часу', _pure.privatIso({ DAT_OD:'28.09.2026' })],
  ['Нова пошта', _pure.npIso('28.09.2026 10:12:00')]
];
дати.forEach(([хто, v]) => {
  ok(/^\d{4}-\d{2}-\d{2}T/.test(v), хто + ' → ' + v,
     хто + ' дав не ISO: ' + v);
});
/* 05.10: Приват і НП кажуть час київський, без поясу. Доти його читали як
   UTC — і в адмінці рух стояв на 2–3 години пізніше. */
ok(_pure.privatIso({ DATE_TIME_DAT_OD_TIM_P:'05.10.2026 14:17:00' }) === '2026-10-05T11:17:00.000Z' &&
   _pure.privatIso({ DATE_TIME_DAT_OD_TIM_P:'01.02.2026 13:45:00' }) === '2026-02-01T11:45:00.000Z' &&
   _pure.npIso('28.09.2026 10:12:00') === '2026-09-28T07:12:00.000Z',
  'час Привату й НП — київський: літо −3 год, зима −2 год до UTC (адмінка покаже рівно 14:17)',
  'час не по Києву: ' + [_pure.privatIso({ DATE_TIME_DAT_OD_TIM_P:'05.10.2026 14:17:00' }), _pure.npIso('28.09.2026 10:12:00')].join(' / '));
ok(_pure.kyivIso(2026, 3, 29, 2, 30, 0) === '2026-03-29T00:30:00.000Z' && _pure.kyivIso(2026, 3, 29, 5, 0, 0) === '2026-03-29T02:00:00.000Z' && _pure.kyivIso(2026, 10, 25, 2, 30, 0) === '2026-10-24T23:30:00.000Z',
  'і в ніч переходу на літній/зимовий час зсув правильний',
  'перехід часу: ' + _pure.kyivIso(2026, 3, 29, 3, 30, 0) + ' / ' + _pure.kyivIso(2026, 10, 25, 2, 30, 0));
ok(_pure.privatIso({ DATE_TIME_DAT_OD_TIM_P:'01.02.2026 13:45:00' }).slice(0, 10) === '2026-02-01',
  'і день з місяцем не міняються місцями: 01.02 — це перше лютого',
  'день і місяць переплутані');

console.log('\n── Накладений платіж: рух лише на виплачене');
/* Гроші, зібрані з отримувача, але ще не переказані нам, — це не гроші на
   рахунку. Рядок на них означав би, що підсумок показує те, чого немає, а
   саме цим числом вирішують, чи вистачає на закупівлю. */
const зібрані = _pure.npPayout({ RedeliverySum:'1500', Number:'204501' });
const виплачені = _pure.npPayout({ RedeliverySum:'1500', MoneyTransferNumber:'99123',
                                   PaymentStatusDate:'28.09.2026 10:00:00' });
console.log('  зібрані: ' + JSON.stringify(зібрані));
console.log('  виплачені: ' + JSON.stringify(виплачені));
ok(зібрані.сума > 0 && !зібрані.переказ,
  'зібране без номера переказу лишається без номера — отже, рядка не буде',
  'зібране виглядає як виплачене');
ok(виплачені.сума > 0 && viplataOk(виплачені),
  'а виплачене має і суму, і номер переказу — саме за цією парою й заводиться рух',
  'виплачене не розпізнається: ' + JSON.stringify(виплачені));
function viplataOk(p){ return !!p.переказ; }
ok(/if \(!p\.сума \|\| !p\.переказ\) (continue|\{[^}]*continue;)/.test(worker),
  'і код перевіряє саме обидві умови, а не одну з них',
  'умова «сума І переказ» у коді не стоїть');

console.log('\n── Імена секретів збігаються з кодами рахунків');
/* `MONO_TOKEN_mono1` знаходить свій рахунок за кодом. Якби коди в адмінці
   називались інакше, воркер мовчки не знайшов би жодного токена. */
const коди = [...admin.matchAll(/\{ id:'(mono\d|privat\d)'/g)].map(m => m[1]);
console.log('  рахунки в адмінці: ' + коди.join(', '));
ok(коди.includes('mono1') && коди.includes('privat1'),
  'рахунки заведені кодами, за якими воркер шукає секрети',
  'кодів рахунків не знайдено: ' + коди.join(', '));
ok(/MONO_TOKEN_' \+ acc/.test(worker) && /PRIVAT_ID_' \+ acc\.id/.test(worker),
  'і воркер складає назву секрета саме з коду рахунку',
  'воркер шукає секрети не за кодом рахунку');
ok(/MONO_TOKEN_mono1/.test(readme) && /PRIVAT_TOKEN_privat1/.test(readme),
  'а в інструкції написано ті самі назви — їх звідти копіюють у консоль',
  'в інструкції інші назви секретів, ніж у коді');

console.log('\n── Нова пошта має свій рахунок у Фінансах');
ok(/np:'Нова пошта/.test(admin),
  'накладений платіж — окремий рахунок: це гроші, просто іншою дорогою',
  'рахунку для накладеного платежу в Фінансах немає');

console.log('\n── У репозиторії немає жодного ключа');
/* Найдорожча помилка цієї роботи — не поломка, а один рядок, залитий у
   репозиторій. Репозиторій читають; токен ФОПа відкриває всі рухи, ключ
   Нової пошти дозволяє створювати накладні за наш рахунок. */
const файли = ['worker/money.js', 'worker/wrangler.money.toml', 'worker/README.md',
               'loomiqadmin.html'];
const підозри = [];
файли.forEach(f => {
  const t = fs.readFileSync(path.join(ROOT, f), 'utf8');
  /* Ключ Нової пошти — 32 шістнадцяткові; токени Моно й Привату — довгі
     рядки base64. Шукаємо їх у присвоєннях, а не будь-де: приклади адрес і
     хеші збірки такими не є. */
  const шаблони = [
    /(MONO_TOKEN|PRIVAT_TOKEN|PRIVAT_ID|NP_API_KEY|HOOK_SECRET|FIREBASE_SA)\s*[:=]\s*["'][^"']{12,}["']/g,
    /["'][a-f0-9]{32}["']\s*[,;]?\s*\/\/\s*(ключ|token|key)/gi,
    /-----BEGIN [A-Z ]*PRIVATE KEY-----/g
  ];
  шаблони.forEach(re => {
    let m;
    while((m = re.exec(t))) підозри.push(f + ': ' + m[0].slice(0, 60));
  });
});
ok(!підозри.length,
  'ні в коді, ні в налаштуваннях, ні в інструкції ключів немає',
  'знайдено схоже на ключ: ' + підозри.join(' | '));
/* І сказано, куди вони кладуться, — інакше наступного разу їх покладуть
   туди, звідки їх видно. */
ok(/wrangler secret put/.test(toml) && /wrangler secret put/.test(readme),
  'а написано, що вони кладуться секретами Cloudflare',
  'ніде не сказано, куди класти доступи');

console.log('\n── Адреси воркера закриті секретом');
ok(/HOOK_SECRET && секрет === env\.HOOK_SECRET/.test(worker),
  'опитування й вебхук не відкриваються тому, хто просто вгадав адресу',
  'адреси воркера відкриті всім');

console.log('\n── Розклад є, бо Приват сам нічого не шле');
ok(/\[triggers\]/.test(toml) && /crons\s*=/.test(toml),
  'опитування вмикається розкладом, а не людиною з кнопкою',
  'розкладу немає — Приват і Нова пошта лишаться неопитаними');
ok(/async scheduled\(/.test(worker),
  'і воркер уміє його приймати',
  'воркер не має обробника розкладу');

console.log('\n── Монобанк: лише рахунок ФОПа, а не особисті картки');
/* Токен Монобанку — людини: з ним видно й особисті картки, і вебхук шле рухи
   по всіх. Пишемо лише рахунок із IBAN, вписаним у Фінансах. */
const ci = { accounts: [
  { id:'card1', iban:'UA213220010000026201234567890', type:'black' },
  { id:'fop1',  iban:'UA903220010000026009876543210', type:'fop' }] };
ok((_pure.monoPick(ci, 'UA90 3220 0100 0002 6009 8765 4321 0') || {}).id === 'fop1',
  'за IBAN із Фінансів (з пробілами чи без) знаходиться саме рахунок ФОПа',
  'рахунок ФОПа за IBAN не знайдено');
ok(_pure.monoPick(ci, '') === null && _pure.monoPick(ci, 'UA000000') === null,
  'без IBAN чи з чужим IBAN — нічого, а не перший-ліпший рахунок',
  'без IBAN узято випадковий рахунок');
ok(/String\(map\[k\]\) === mono/.test(worker) && /if \(!куди\) return 0;/.test(worker),
  'вебхук кладе рух у той рахунок Фінансів, якому належить рахунок Монобанку; незаведений — не пише',
  'вебхук пише рухи всіх рахунків людини');

console.log(bad ? '\n✗ провалено перевірок: ' + bad
                : '\nворкер і адмінка домовились; ключів у репозиторії немає');
process.exit(bad ? 1 : 0);
