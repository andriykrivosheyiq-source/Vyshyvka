/* ОДИН ДИЗАЙН — ОДНА РОЗМОВА, СВОЇ ВЕРСІЇ, СВІЙ ВІДПОВІДАЛЬНИЙ.

   Доти правки й версії жили на всьому замовленні. На замовленні з двома-
   трьома нанесеннями це відразу ламалось: «переробіть, завеликий» — а що
   завелике? «Версія 2» — чого версія? Дизайнер мусив вгадувати.

   Тепер найдрібніша одиниця роботи — ОДНЕ НАНЕСЕННЯ: логотип на груди,
   напис на спину. Про нього менеджер пише правку, його малює дизайнер, його
   показують клієнту, і в нього свої версії.

   Перевіряємо саме те, заради чого це заводилось:

     1. ПРАВКА ЛЕЖИТЬ ПРИ СВОЄМУ ДИЗАЙНІ, а не в спільній купі.
     2. ВЕРСІЇ НУМЕРУЮТЬСЯ ПО ДИЗАЙНУ — і в графічних, і у вишивальних.
     3. НЕПРОЧИТАНЕ РАХУЄТЬСЯ НА ЛЮДИНУ: своє власне повідомлення не
        буває непрочитаним, чуже — буває, поки не відкрив.
     4. ВИШИВАЛЬНОМУ НЕ ПЕРЕДАТИ, доки графіку не затверджено: оцифрувати
        те, що ще поміняють, — це викинута робота.
     5. ЗАТВЕРДИТИ МОЖЕ І КЛІЄНТ, І АКАУНТ-МЕНЕДЖЕР — обидва читають ту саму
        переписку, і чекати саме клієнтського слова означало б спинити
        роботу через формальність.

   Модуль тут крутиться сам, без браузера: усе це чиста робота з даними, а
   сторінка лише сповільнила б перевірку.

   Запуск:  node tests/design-thread.mjs      (з кореня репозиторію)  */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

globalThis.window = globalThis;
globalThis.document = { createElement: () => ({ getContext: () => null }) };
new Function(fs.readFileSync(path.join(ROOT, 'loomiq-design.js'), 'utf8'))();
const D = window.LQDesign;

let bad = 0;
const ok = (cond, good, wrong) => {
  console.log('  ' + (cond ? good + ' ✓' : wrong + ' ✗')); if(!cond) bad++;
};

const МЕНЕДЖЕР = 'acct@loomiq', ГРАФІК = 'graphic@loomiq', ВИШИВКА = 'stitch@loomiq';
const одиниця = () => {
  const u = { id:'u1', gid:'hoodie', name:'Худі', color:'', size:'', qty:5,
              pics:[], graphic:[], stitch:[], note:'' };
  D.dzList(u, 'graphic').push(D.dzNew(), D.dzNew());
  D.dzList(u, 'stitch').push(D.dzNew());
  u.graphic[0].name = 'Лого на груди';
  u.graphic[1].name = 'Напис на спину';
  u.stitch[0].name = 'Лого на груди';
  return u;
};

/* ── 1. Правка належить своєму дизайну ──────────────────────────────── */
console.log('\n── Правка лежить при своєму нанесенні');
{
  const u = одиниця();
  D.dzSay(u.graphic[0], МЕНЕДЖЕР, 'Клієнт: лого завелике, зменшіть на третину', null);
  ok(u.graphic[0].thread.length === 1 && !u.graphic[1].thread.length,
     'правка стоїть на тому нанесенні, якого стосується',
     'правка розповзлась на сусідній дизайн');
  ok(/завелике/.test(u.graphic[0].thread[0].text),
     'слова клієнта лежать дослівно — їх і скопіювали з переписки',
     'текст правки загубився');
}

/* ── 2. Версії по дизайну, в обох видах ─────────────────────────────── */
console.log('\n── Версії нумеруються по дизайну');
{
  const u = одиниця();
  D.dzVer(u.graphic[0], ГРАФІК, { name:'лого-v1.png', url:'https://cdn/v1.png' }, '');
  D.dzVer(u.graphic[0], ГРАФІК, { name:'лого-v2.png', url:'https://cdn/v2.png' }, '');
  D.dzVer(u.graphic[1], ГРАФІК, { name:'напис-v1.png', url:'https://cdn/n1.png' }, '');
  ok(u.graphic[0].vers.map(v => v.n).join() === '1,2' &&
     u.graphic[1].vers.map(v => v.n).join() === '1',
     'у кожного нанесення власна нумерація: 1,2 і 1',
     'нумерація змішалась: ' + JSON.stringify([u.graphic[0].vers.map(v=>v.n),
                                               u.graphic[1].vers.map(v=>v.n)]));
  /* Вишивальні файли теж повертають на переробку — версії потрібні й тут. */
  D.dzVer(u.stitch[0], ВИШИВКА, { name:'лого.dst', url:'https://cdn/a.dst' }, '');
  ok(u.stitch[0].vers.length === 1,
     'у вишивального дизайну версії свої, як і в графічного',
     'вишивальний дизайн лишився без версій');
}

/* ── 3. Непрочитане рахується на людину ─────────────────────────────── */
console.log('\n── Непрочитане');
{
  const u = одиниця();
  const d = u.graphic[0];
  D.dzSay(d, МЕНЕДЖЕР, 'Зменшіть лого', null);
  D.dzSay(d, МЕНЕДЖЕР, 'І посуньте вище', null);
  ok(D.dzUnseen(d, ГРАФІК) === 2, 'дизайнер бачить дві непрочитані правки',
     'непрочитаних у дизайнера ' + D.dzUnseen(d, ГРАФІК) + ' замість 2');
  ok(D.dzUnseen(d, МЕНЕДЖЕР) === 0,
     'своє власне повідомлення непрочитаним не буває',
     'менеджеру показує його ж власні правки як непрочитані');
  D.dzSeen(d, ГРАФІК);
  ok(D.dzUnseen(d, ГРАФІК) === 0, 'відкрив — отже прочитав',
     'після відкриття непрочитане лишилось');
  D.dzVer(d, ГРАФІК, { name:'v1.png', url:'https://cdn/v1.png' }, '');
  ok(D.dzUnseen(d, МЕНЕДЖЕР) === 1,
     'нова версія від дизайнера — непрочитане вже в менеджера',
     'менеджер не бачить, що прийшла версія');
}

/* ── 4. Вишивальному — тільки після затвердження графіки ────────────── */
console.log('\n── Ворота перед вишивальним дизайном');
{
  const u = одиниця();
  ok(!D.graphicOk(u), 'поки графіку не затверджено — передавати нема чого',
     'ворота відкриті з самого початку: оцифруємо те, що ще поміняється');
  D.dzOk(u.graphic[0], МЕНЕДЖЕР, 'acct');
  ok(!D.graphicOk(u), 'одного затвердженого з двох замало',
     'ворота відкрились на половині графіки');
  D.dzOk(u.graphic[1], МЕНЕДЖЕР, 'client');
  ok(D.graphicOk(u), 'уся графіка затверджена — вишивальному можна передавати',
     'ворота не відкрились, хоч уся графіка затверджена');
  /* Виріб без графіки взагалі — чекати нема на що: буває вишивка з готового
     файлу клієнта, і зупиняти її неіснуючим затвердженням безглуздо. */
  ok(D.graphicOk({ id:'u2', graphic:[], stitch:[] }),
     'на виробі без графіки ворота не заважають',
     'виріб без графіки застряг у воротах назавжди');
}

/* ── 5. Затвердити може і клієнт, і акаунт-менеджер ─────────────────── */
console.log('\n── Хто затверджує');
{
  const u = одиниця();
  const d = u.graphic[0];
  D.dzVer(d, ГРАФІК, { name:'v1.png', url:'https://cdn/v1.png' }, '');
  D.dzVer(d, ГРАФІК, { name:'v2.png', url:'https://cdn/v2.png' }, '');
  D.dzOk(d, МЕНЕДЖЕР, 'client', 2);
  ok(d.ok && d.ok.how === 'client' && d.ok.ver === 2 && d.status === 'approved',
     'записано, ЩО саме затверджено: клієнт, версія 2',
     'затвердження записалось не так: ' + JSON.stringify(d.ok));
  /* Номер обраної версії важить: клієнт сказав «беремо другу», і другою має
     лишитись саме та, яку він бачив, хай далі буде хоч пʼята. */
  D.dzVer(d, ГРАФІК, { name:'v3.png', url:'https://cdn/v3.png' }, '');
  ok(d.ok.ver === 2, 'нова версія обраної не зрушила',
     'обрана версія поїхала на нову');
  D.dzUnok(d);
  ok(!d.ok && d.status !== 'approved', 'затвердження можна зняти',
     'зняти затвердження не вийшло');
}

/* ── 6. Правка повертає дизайн у роботу ─────────────────────────────── */
console.log('\n── Стан іде за роботою');
{
  const u = одиниця();
  const d = u.graphic[0];
  D.dzSend(d, ГРАФІК, МЕНЕДЖЕР);
  ok(d.who === ГРАФІК && d.status === 'work',
     'передали конкретній людині — дизайн у роботі',
     'передача не спрацювала: ' + d.who + '/' + d.status);
  D.dzVer(d, ГРАФІК, { name:'v1.png', url:'https://cdn/v1.png' }, '');
  ok(d.status === 'review', 'здав версію — на перевірці',
     'стан після версії: ' + d.status);
  D.dzSay(d, МЕНЕДЖЕР, 'Ще трохи менше', null);
  ok(d.status === 'revision',
     'прийшла правка — знову в роботі, а не «на перевірці»',
     'після правки дизайн лишився на перевірці: ' + d.status);
}

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\n✓ усе гаразд');
process.exit(bad ? 1 : 0);
