/* РОЗДРІБНА ЦІНА Й ДОДАТКОВІ ПОСЛУГИ ЗАДАЮТЬСЯ РАЗ.

   У корпоративному замовленні ціна — машина: шкала за тиражем, площа
   нанесення в квадратних міліметрах, поділ підготовки макета між виробами,
   ескізи, допродажі. Вона там потрібна: замовлення на двісті штук інакше не
   порахувати.

   У приватному нічого з цього немає. Андрій: «там логіки практично ніякої
   немає, просто вибираєш товар, і на цьому все». Тягнути туди двигун B2B
   означало б рахувати знижку за тираж на одній футболці.

   Тому роздріб — це два простих списки:
     • ціна виробу, одне число в картці товару (порожнє = базова);
     • додаткові послуги — назва й ціна, задані раз у налаштуваннях.

   Перевіряємо, що обидва справді є, зберігаються й читаються назад. Без
   цього менеджер вписував би ціну щоразу руками, і та сама робота коштувала
   б у чотирьох замовленнях по-різному.

   Запуск:  node tests/retail-price.mjs      (з кореня репозиторію)  */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const H = fs.readFileSync(path.join(ROOT, 'loomiqadmin.html'), 'utf8');

let bad = 0;
const ok = (c, good, wrong) => { console.log('  ' + (c ? good + ' ✓' : wrong + ' ✗')); if(!c) bad++; };

console.log('\n── Ціна виробу в роздріб');
ok(/id="pc-retail"/.test(H),
  'поле стоїть у картці товару, поруч із базовою ціною й собівартістю',
  'поля роздрібної ціни немає');
ok(/upd\.products\.retail\[id\]/.test(H),
  'і зберігається разом із рештою цін товару',
  'роздрібна ціна нікуди не зберігається');
ok(/retEl\.value/.test(H) && /prod\.retail/.test(H),
  'а при відкритті картки читається назад',
  'збережена ціна не повертається в поле');
/* Порожнє поле — це «як базова», а не нуль. Нуль означав би безкоштовний
   виріб, і замовлення мовчки порахувалось би в нуль. */
ok(/placeholder="як базова"/.test(H),
  'порожнє поле чесно каже, що тоді береться базова ціна',
  'порожнє поле нічого не пояснює — його приймуть за нуль');

console.log('\n── Додаткові послуги');
ok(/id="sp-extras"/.test(H) && /id="sp-extra-add"/.test(H),
  'список послуг є в налаштуваннях, і до нього можна додати рядок',
  'списку додаткових послуг немає');
ok(/function readExtras\(/.test(H) && /function paintExtras\(/.test(H),
  'він читається й малюється',
  'послуги нічим прочитати або намалювати');
ok(/extras:\s*readExtras\(\)/.test(H),
  'і зберігається окремим блоком налаштувань B2C',
  'послуги не зберігаються');
ok(/paintExtras\(c\.extras\)/.test(H),
  'а при відкритті налаштувань повертається назад',
  'збережені послуги не повертаються');
/* Рядок без назви — це забутий рядок, а не послуга. Інакше менеджер бачив
   би в списку вибору порожній пункт і гадав, що це. */
ok(/filter\(x => x\.name\)/.test(H),
  'порожні рядки в список не потрапляють',
  'порожній рядок зберігається як послуга');

console.log('\n── Дані для накладної');
const D = fs.readFileSync(path.join(ROOT, 'loomiq-design.js'), 'utf8');
['name','phone','city','office'].forEach(k => {
  ok(new RegExp("поле\\('" + k + "'").test(D), 'поле «' + k + '» є',
     'поля «' + k + '» для накладної немає');
});
ok(/data-sf=/.test(D) && /c\.o\.ship\[el\.dataset\.sf\]/.test(D),
  'дані лежать разом, одним полем замовлення — їх завжди потрібно гуртом',
  'дані накладної нікуди не зберігаються');

console.log('\n── Гроші замовлення');
ok(/function moneyHtml\(/.test(D) && /data-of="prepaid"/.test(D),
  'сума, передоплата й залишок стоять у картці',
  'блока грошей у картці немає');
ok(/Залишок до оплати/.test(D),
  'залишок порахований, а не лишений на усний рахунок',
  'залишку до оплати не видно');

console.log(bad ? '\n✗ провалено перевірок: ' + bad : '\nроздрібні ціни задаються раз і повертаються назад');
process.exit(bad ? 1 : 0);
