/* ПЕРЕВІРКА ПРОРАХУНКУ КОНКРЕТНОГО ЗАМОВЛЕННЯ.

   Вхід — файл, який дає кнопка «Зберегти прорахунок» у картці замовлення
   («Фінанси» → «Як склалась ціна»). У ньому лежить усе, з чого рушій робить
   ціну, і все, що він повернув.

   Тут це перераховується НАНОВО тим самим рушієм (loomiq-pricing.js) і
   звіряється по чотирьох напрямках:

     1. Перерахунок наново = ціни, збережені в замовленні. Розійшлись — ціна
        в картці застаріла: її рахували за іншою моделлю або іншим складом.
     2. Рядки розкладу додаються в «Ціну за штуку». Розклад, який не
        сходиться сам із собою, — це не пояснення, а друга версія ціни.
     3. Разова за дизайн = сума часток за видами плюс ескізи. Саме це число
        ділиться на одиниці, і саме воно зазвичай і виглядає «дивним».
     4. Сума основних позицій + ручна поправка = сума замовлення.

   Плюс друкує розклад дизайнів: який відбиток, яким видом рахується, чи
   слово це менеджера, на скільки виробів ділиться його разова і скільки
   таких дизайнів у групі. Поділ разових без цієї таблиці не перевірити.

   Запуск:  node tools/check-calc.mjs прорахунок-1000057.json            */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = process.argv[2];
if(!file){
  console.error('Вкажіть файл: node tools/check-calc.mjs прорахунок-1000057.json');
  process.exit(2);
}
let D;
try{ D = JSON.parse(fs.readFileSync(path.resolve(file), 'utf8')); }
catch(e){ console.error('Не читається файл: ' + (e && e.message || e)); process.exit(2); }

/* Рушій написаний для браузера й читає window.SITE_CONTENT.pricing. Даємо
   йому рівно те вікно, яке він очікує, — жодних заглушок понад це. */
globalThis.window = globalThis;
const модель = (D.модельЦін && (D.модельЦін.рушія || D.модельЦін.адмінки)) || D.модельЦін || null;
globalThis.SITE_CONTENT = { pricing: модель };
new Function(fs.readFileSync(path.join(ROOT, 'loomiq-pricing.js'), 'utf8'))();
const LQ = globalThis.LQ;

const чек = [];
const note = (добре, текст) => { chalk(добре, текст); if(!добре) чек.push(текст); };
function chalk(добре, текст){ console.log('  ' + (добре ? '· ' : '✗ ') + текст); }
const грн = n => (n == null ? '—' : n + ' ₴');

const зам = D.замовлення || {};
console.log('══ ЗАМОВЛЕННЯ ' + (зам.номер || '—') +
            (зам.напрям ? ' · ' + зам.напрям : '') + ' ══');
console.log('  знято за ' + (D.коли || '—') + (D.збірка ? ' · збірка ' + D.збірка : ''));
if(зам.безОплатиЗаДизайн) console.log('  «за дизайн не беремо» — увімкнено');
if(зам.ручнаПоправка) console.log('  ручна поправка до суми: ' + грн(зам.ручнаПоправка));
if(!модель) console.log('  ⚠ моделі цін у файлі немає — перерахунок наново неможливий');

const позиції = D.позиції || [];
const вхід = (D.рушій && D.рушій.вхід) || [];
const вихід = (D.рушій && D.рушій.вихід) || [];
const уПрогоні = позиції.filter(x => x.уПрогоні);

/* ── 1. Перерахунок наново ─────────────────────────────────────────────── */
console.log('');
console.log('══ ПЕРЕРАХУНОК НАНОВО ══');
let свіжі = null;
if(модель && вхід.length){
  try{ свіжі = LQ.priceOrder(вхід, (D.рушій && D.рушій.умови) || {}); }
  catch(e){ console.log('  ✗ рушій упав: ' + (e && e.message || e)); чек.push('рушій упав'); }
}
if(свіжі){
  уПрогоні.forEach((it, k) => {
    const r = свіжі[k];
    if(!r){ note(false, it.назва + ': рушій не повернув нічого'); return; }
    note(r.unit === it.заШтуку,
      it.назва + ': ' + грн(r.unit) + ' за штуку' +
      (r.unit === it.заШтуку ? '' : ', а в замовленні ' + грн(it.заШтуку) +
        ' — ціна в картці застаріла на ' + (it.заШтуку - r.unit) + ' ₴'));
    if(it.розклад && r.parts && r.parts.feeShare !== it.розклад.feeShare)
      note(false, it.назва + ': разова за дизайн наново ' + грн(r.parts.feeShare) +
                  ', а збережена ' + грн(it.розклад.feeShare));
  });
} else if(модель){
  console.log('  (у прогоні немає жодної позиції)');
}

/* ── 2. Розклад додається в ціну ───────────────────────────────────────── */
console.log('');
console.log('══ РОЗКЛАД ДОДАЄТЬСЯ В ЦІНУ ══');
const екран = D.розкладНаЕкрані || [];
if(!екран.length) console.log('  (розкладу у файлі немає)');
екран.forEach((card, k) => {
  const рядки = card.рядки || [];
  const стар = рядки.length && typeof рядки[0] === 'string';
  if(стар){ console.log('  ⚠ ' + card.позиція + ': старий формат файла, рядки не звірити'); return; }
  const доданки = рядки.filter(r => r.рід === 'доданок' || r.рід === 'знижка');
  const підсумки = рядки.filter(r => r.рід === 'підсумок');
  const сума = доданки.reduce((a, r) => a + r.число, 0);
  const заШтуку = підсумки[0] ? підсумки[0].число : null;
  const заТираж = підсумки[1] ? підсумки[1].число : null;
  note(сума === заШтуку,
    card.позиція + ': рядки дають ' + грн(сума) +
    (сума === заШтуку ? ', і це ціна за штуку' : ', а «ціна за штуку» ' + грн(заШтуку)));
  const it = уПрогоні[k];
  if(it){
    if(заШтуку !== it.заШтуку)
      note(false, card.позиція + ': у розкладі ' + грн(заШтуку) +
                  ' за штуку, у позиції ' + грн(it.заШтуку));
    if(заТираж !== it.сума)
      note(false, card.позиція + ': у розкладі ' + грн(заТираж) +
                  ' за тираж, у позиції ' + грн(it.сума));
    if(it.заШтуку * it.тираж !== it.сума)
      note(false, card.позиція + ': ' + it.заШтуку + ' × ' + it.тираж + ' ≠ ' + it.сума);
  }
});

/* ── 2b. Склад пропозиції: рекомендовані й групи варіантів ─────────────
   Екран збирання рахує НЕ ТЕ САМЕ, що картка. Там, крім основних позицій,
   стоять рекомендовані — кожна як «склад + вона», — і групи варіантів, з
   яких клієнт візьме одну. Через це сума не число, а вилка. Саме ці числа
   найчастіше й перевіряють, бо саме їх менеджер бачить на екрані. */
const проп = D.розкладПропозиції;
if(проп){
  console.log('');
  console.log('══ СКЛАД ПРОПОЗИЦІЇ ══');
  if((проп.groups || []).length)
    console.log('  тираж груп: ' + проп.groups.map(g => g.k + ' ' + g.q + ' шт').join(' · '));
  const цифра = t => {
    const m = String(t).replace(/\u2212/g, '-').replace(/\s/g, '').match(/-?\d+/);
    return m ? +m[0] : 0;
  };
  const блок = (назва, box) => {
    const rows = (box && box.rows) || [];
    if(!rows.length){ note(false, назва + ': розкладу немає зовсім'); return; }
    /* «sub» — це підрядок уже порахованого доданка (↳ площа, ↳ старт,
       ↳ у цьому тиражі). Складати їх із батьківським рядком означало б
       порахувати ті самі гроші двічі. */
    const дод = rows.filter(r => r[2] !== 'sum' && r[2] !== 'sub');
    const сум = rows.filter(r => r[2] === 'sum');
    const сума = дод.reduce((a2, r) => a2 + цифра(r[1]), 0);
    const заШтуку = сум[0] ? цифра(сум[0][1]) : null;
    const заТираж = сум[1] ? цифра(сум[1][1]) : null;
    console.log('  ' + назва + ' · ' + box.qty + ' шт × ' + заШтуку + ' ₴ = ' + грн(box.price));
    note(сума === заШтуку,
      '   рядки дають ' + грн(сума) +
      (сума === заШтуку ? ', і це ціна за штуку' : ', а «ціна за штуку» ' + грн(заШтуку)));
    if(заТираж !== (+box.price || 0))
      note(false, '   у розкладі ' + грн(заТираж) + ' за тираж, у позиції ' + грн(box.price));
    if(заШтуку != null && заШтуку * (+box.qty || 0) !== (+box.price || 0))
      note(false, '   ' + заШтуку + ' × ' + box.qty + ' ≠ ' + box.price);
  };
  const пройти = (тег, набір) => Object.keys(набір || {}).forEach(k =>
    блок(тег + (набір[k].name ? ' · ' + набір[k].name : ' №' + k), набір[k]));
  пройти('основна', проп.items);
  пройти('варіант', проп.vars);
  пройти('рекомендована', проп.reco);
  if(проп.sum)
    note(проп.sum.price === (позиції.filter(x => x.рід === 'main')
                               .reduce((a2, x) => a2 + Math.round(+x.сума || 0), 0)),
      'сума основних на екрані ' + грн(проп.sum.price) + ' — і стільки ж у позиціях');
}

/* ── 2c. Вилка «від — до» ──────────────────────────────────────────────── */
const вилка = D.вилка;
if(вилка && Object.keys(вилка.групи || {}).length){
  console.log('');
  console.log('══ ВИЛКА СУМИ ══');
  console.log('  основні: ' + грн(вилка.основні) + ' · ' + вилка.штукОсновних + ' шт');
  let lo = 0, hi = 0;
  Object.keys(вилка.групи).forEach(g => {
    const list = вилка.групи[g];
    const sums = list.map(x => x.сума);
    const min = Math.min.apply(null, sums), max = Math.max.apply(null, sums);
    lo += min; hi += max;
    console.log('  ' + g + ': ' + list.map(x => x.назва + ' ' + грн(x.сума)).join(' · ') +
                '  → від ' + грн(min) + ' до ' + грн(max));
    const тиражі = list.map(x => x.тираж);
    note(тиражі.every(q => q === тиражі[0]),
      '   усі варіанти групи рахуються від того самого тиражу (' + тиражі.join(', ') + ')');
  });
  note(вилка.основні + lo === вилка.від && вилка.основні + hi === вилка.до,
    'вилка: ' + грн(вилка.основні + lo) + ' – ' + грн(вилка.основні + hi) +
    ' · ' + (вилка.штукОсновних + вилка.штукУГрупах) + ' шт' +
    (вилка.основні + lo === вилка.від && вилка.основні + hi === вилка.до
      ? '' : ', а на екрані ' + грн(вилка.від) + ' – ' + грн(вилка.до)));
}

/* ── 3. Разова за дизайн ───────────────────────────────────────────────── */
console.log('');
console.log('══ РАЗОВА ЗА ДИЗАЙН ══');
const UA = { img:'картинка', txt:'напис', off:'не рахуємо' };
const слово = (D.видДизайну && D.видДизайну.словоМенеджера) || {};
позиції.forEach(it => {
  const b = it.розклад;
  if(!b) return;
  const fl = b.feeLines || [], sk = b.sketches || [];
  if(!fl.length && !sk.length && !b.feeShare) return;
  console.log('  ' + it.назва + ' × ' + it.тираж + ' шт:');
  fl.forEach(l => console.log('     підготовка · ' + (UA[l.kind] || l.kind) + ' · ' +
    l.fee + ' ₴ ÷ ' + l.units + ' шт = ' + Math.round(l.fee / (l.units || 1)) + ' ₴/шт'));
  sk.forEach(x => console.log('     ескіз №' + x.no + ' · ' + (UA[x.kind] || x.kind) + ' · ' +
    x.fee + ' ₴ ÷ ' + x.units + ' шт = ' + Math.round(x.fee / (x.units || 1)) + ' ₴/шт'));
  const точно = fl.reduce((a, l) => a + l.fee / (l.units || 1), 0) +
                sk.reduce((a, x) => a + x.fee / (x.units || 1), 0);
  note(Math.round(точно) === (+b.feeShare || 0),
    '   разом ' + грн(Math.round(точно)) +
    (Math.round(точно) === (+b.feeShare || 0)
      ? ' — стільки й у ціні'
      : ', а в ціні ' + грн(b.feeShare)));
  if(it.ділятьРазову) console.log('     у цьому тиражі: ' + it.ділятьРазову);
});

/* ── 3b. ПОДІЛ РАЗОВИХ — ГОЛОВНЕ ───────────────────────────────────────
   Підготовка макета і додатковий ескіз — це разові гроші: платять їх РАЗ на
   все замовлення, а в ціні вони стоять часткою на кожній одиниці. Отже
   перевіряти треба не саму частку, а знаменник: на скільки виробів вона
   ділиться і чи ті це вироби.

   Правила рушія, які тут і звіряються:
     • підготовка виду ділиться на ВСІ вироби прогону, де цей вид є;
     • ескіз ділиться лише на вироби СВОЄЇ групи дизайнів;
     • перша група виду входить у підготовку, кожна наступна — рівно один
       ескіз на все замовлення, а не по одному на позицію;
     • усі написи способу — один дизайн: друга підготовка за напис не
       береться ніколи;
     • рекомендована рахується як «склад + вона», тож її знаменник більший
       за складовий рівно на її тираж. */
console.log('');
console.log('══ ПОДІЛ РАЗОВИХ ══');
const позаНомером = {};
позиції.forEach((x, i) => { позаНомером[i] = x; });
const метод = x => ((x.опис || {}).method === 'embro') ? 'embro' : 'dtf';
const видиПозиції = x => {
  const d = x.опис || {};
  const out = {};
  (d.designKinds || []).forEach(k => { if(k && k !== 'off') out[k] = 1; });
  return out;
};
if(!позиції.some(x => x.прогін))
  console.log('  ⚠ у файлі немає складу прогонів — збережіть прорахунок ще раз, ' +
              'цей файл знятий старою версією');
позиції.forEach((it, i) => {
  const b = it.розклад;
  if(!b || (!(b.feeLines || []).length && !(b.sketches || []).length)) return;
  const run = (it.прогін || []).map(n => позаНомером[n]).filter(Boolean);
  if(!run.length) return;
  console.log('  ' + it.назва + ' × ' + it.тираж + ' шт · рахувалась із: ' +
    run.map(x => x.назва + ' ×' + x.тираж).join(' · '));

  (b.feeLines || []).forEach(l => {
    /* Знаменник підготовки — усі вироби прогону того самого способу, у яких
       цей вид дизайну взагалі є. */
    const свої = run.filter(x => метод(x) === метод(it) && !(x.опис || {}).bare &&
                                 видиПозиції(x)[l.kind]);
    const треба = свої.reduce((a2, x) => a2 + (+x.тираж || 0), 0);
    note(треба === l.units,
      '   підготовка · ' + (UA[l.kind] || l.kind) + ' · ' + l.fee + ' ₴ ÷ ' + l.units +
      ' шт' + (треба === l.units
        ? ' = ' + свої.map(x => x.назва + ' ' + x.тираж).join(' + ')
        : ' — а виробів із цим видом ' + треба + ': ' +
          свої.map(x => x.назва + ' ' + x.тираж).join(' + ')));
  });

  (b.sketches || []).forEach(sk => {
    /* Знаменник ескізу — вироби прогону, у яких є САМЕ ця група дизайнів.
       Групу впізнаємо за номером, який рушій проставив у designNos: усередині
       одного прогону нумерація спільна. */
    const свої = run.filter(x => {
      const nos = ((x.розклад || {}).designNos) || [];
      return метод(x) === метод(it) &&
             nos.some(d => d && d.kind === sk.kind && d.no === sk.no);
    });
    const треба = свої.reduce((a2, x) => a2 + (+x.тираж || 0), 0);
    note(треба === sk.units || !свої.length,
      '   ескіз №' + sk.no + ' · ' + (UA[sk.kind] || sk.kind) + ' · ' + sk.fee + ' ₴ ÷ ' +
      sk.units + ' шт' + (треба === sk.units || !свої.length
        ? (свої.length ? ' = ' + свої.map(x => x.назва + ' ' + x.тираж).join(' + ') : '')
        : ' — а виробів цієї групи ' + треба + ': ' +
          свої.map(x => x.назва + ' ' + x.тираж).join(' + ')));
  });
});

/* Скільки разів разова взялась на все замовлення. Саме це питання і стоїть
   за «дивно ділить»: одна підготовка чи дві, один ескіз чи по одному на
   кожній позиції. Рахуємо по ГОЛОВНОМУ прогону — рекомендовані рахуються
   окремо, і складати їх сюди означало б порахувати склад двічі. */
const склад = позиції.filter(x => x.уПрогоні);
if(склад.length){
  console.log('');
  console.log('  ── скільки разів разова взялась на все замовлення ──');
  const відра = {};
  склад.forEach(x => {
    const b = x.розклад; if(!b) return;
    (b.feeLines || []).forEach(l => {
      const k = метод(x) + ':' + l.kind + ':підготовка';
      (відра[k] = відра[k] || { fee:l.fee, взято:0, хто:[] });
      відра[k].взято += (l.fee / (l.units || 1)) * (+x.тираж || 0);
      відра[k].хто.push(x.назва);
    });
    (b.sketches || []).forEach(sk => {
      const k = метод(x) + ':' + sk.kind + ':ескіз №' + sk.no;
      (відра[k] = відра[k] || { fee:sk.fee, взято:0, хто:[] });
      відра[k].взято += (sk.fee / (sk.units || 1)) * (+x.тираж || 0);
      відра[k].хто.push(x.назва);
    });
  });
  Object.keys(відра).forEach(k => {
    const v = відра[k];
    const p = k.split(':');
    note(Math.abs(v.взято - v.fee) < 1,
      '   ' + p[2] + ' · ' + (UA[p[1]] || p[1]) + ' · ставка ' + v.fee + ' ₴, ' +
      'зібрано із замовлення ' + Math.round(v.взято) + ' ₴' +
      (Math.abs(v.взято - v.fee) < 1 ? ' — рівно один раз'
        : ' — це ' + (v.взято / (v.fee || 1)).toFixed(2) + ' ставки (' + v.хто.join(', ') + ')'));
  });
}

/* Написи способу — один дизайн. Друга підготовка за напис не береться
   ніколи, і ескізів за написи не буває взагалі. */
const написи = {};
позиції.forEach(x => {
  ((x.розклад || {}).designNos || []).forEach(d => {
    if(!d || d.kind !== 'txt') return;
    (написи[метод(x)] = написи[метод(x)] || {})[d.no] = 1;
  });
});
Object.keys(написи).forEach(mk => {
  const nos = Object.keys(написи[mk]);
  note(nos.length === 1,
    '   усі написи (' + mk + ') — один дизайн' +
    (nos.length === 1 ? '' : ', а їх тут ' + nos.length + ' (групи ' + nos.join(', ') + ')'));
});
const ескізиНаписів = позиції.some(x =>
  ((x.розклад || {}).sketches || []).some(sk => sk.kind === 'txt'));
if(ескізиНаписів) note(false, '   за напис виставлено додатковий ескіз — за написи їх не буває');

/* Рекомендована рахується «склад + вона»: її знаменник більший за
   складовий рівно на її тираж. */
позиції.filter(x => x.рід === 'reco').forEach(r => {
  (((r.розклад || {}).feeLines) || []).forEach(l => {
    const свої = склад.filter(x => метод(x) === метод(r) && !(x.опис || {}).bare &&
                                   видиПозиції(x)[l.kind]);
    const базово = свої.reduce((a2, x) => a2 + (+x.тираж || 0), 0);
    note(l.units === базово + (+r.тираж || 0),
      '   рекомендована «' + r.назва + '» ділить ' + (UA[l.kind] || l.kind) +
      ' на ' + l.units + ' шт' +
      (l.units === базово + (+r.тираж || 0)
        ? ' = склад ' + базово + ' + вона ' + r.тираж
        : ' — а мало б бути ' + (базово + (+r.тираж || 0)) +
          ' (склад ' + базово + ' + вона ' + r.тираж + ')'));
  });
});

/* ── Дизайни: що з чим склеїлось ───────────────────────────────────────── */
console.log('');
console.log('══ ДИЗАЙНИ: ЩО З ЧИМ СКЛЕЇЛОСЬ ══');
позиції.forEach(it => {
  const d = it.опис, b = it.розклад;
  if(!d || !(d.designs || []).length) return;
  console.log('  ' + it.назва + ':');
  (d.designs || []).forEach((fp, i) => {
    const no = ((b && b.designNos) || []).find(x => x.i === i) || {};
    const вид = (d.designKinds || [])[i] || '—';
    const ключ = String(fp || '');
    console.log('     №' + (i + 1) + ' ' + (UA[вид] || вид) +
      (слово[ключ] ? ' (слово менеджера)' : ' (автоматично)') +
      ' · відбиток ' + ключ.slice(0, 10) + '…' +
      (no.no ? ' · група ' + no.no + (no.first ? ' (перша — входить у підготовку)' : ' (платний ескіз)') : '') +
      (no.units ? ' · ділиться на ' + no.units + ' шт' : ''));
  });
  if(b && b.freeDesigns) console.log('     ' + b.freeDesigns + ' дизайн(и) вже оплачено раніше');
  if(b && b.offDesigns) console.log('     ' + b.offDesigns + ' дизайн(и) не рахуємо');
});

